package practice;
import java.util.*;

public class Convert_Kilometers_to_Miles {

	public static void main(String[] args) {
		Scanner sc=new Scanner(System.in);
		System.out.print("distance in km= ");
		double k=sc.nextDouble();
		double m=k*0.621317;
		System.out.println("distance in miles= "+m);
		

	}

}
