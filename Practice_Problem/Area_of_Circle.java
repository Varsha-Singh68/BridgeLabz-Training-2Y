package practice;
import java.util.*;

public class Area_of_Circle {

	public static void main(String[] args) {
		final double Pi=3.14;
		Scanner sc=new Scanner(System.in);
		System.out.print("enter radius= ");
		int r=sc.nextInt();
		double a=Pi*r*r;
		System.out.println("Area of circle= "+a);
		
		

	}

}
